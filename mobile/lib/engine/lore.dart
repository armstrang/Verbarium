/// The lore of every title and every job, told short. The full lore is the document "Kitab Lore Verbarium";
/// this file holds what the app shows: the introduction after a coronation and the story behind a tapped figure.
///
/// The world in one breath: in Verbarium everything lasts as long as its name is remembered. The Fog of
/// Forgetting fades whatever is no longer spoken; the Great Chronicle records every word a person holds, and
/// titles come from what it records, not from birth. The player is the Chronicler, a field child who learns
/// words so that the things they love do not vanish. Each realm is guarded by the broken shadow of the title
/// that lies ahead.
library;

import '../app/lang.dart';

class Lore {
  final String _quote, _quoteEn, _story, _storyEn, _nature, _natureEn, _past, _pastEn, _drive, _driveEn;

  /// Spanish, French, German and Portuguese, each in order: quote, story, nature, past, drive
  final List<String> _es, _fr, _de, _pt;
  const Lore(
    this._quote,
    this._quoteEn,
    this._story,
    this._storyEn,
    this._nature,
    this._natureEn,
    this._past,
    this._pastEn,
    this._drive,
    this._driveEn,
    this._es,
    this._fr,
    this._de,
    this._pt,
  );

  String _t(String id, String en, int i) => tr(id, en, _es[i], _fr[i], _de[i], _pt[i]);
  String get quote => _t(_quote, _quoteEn, 0);
  String get story => _t(_story, _storyEn, 1);
  String get nature => _t(_nature, _natureEn, 2);
  String get past => _t(_past, _pastEn, 3);
  String get drive => _t(_drive, _driveEn, 4);

  /// every text in every language, for the test
  List<String> get all => [
    _quote,
    _quoteEn,
    _story,
    _storyEn,
    _nature,
    _natureEn,
    _past,
    _pastEn,
    _drive,
    _driveEn,
    ..._es,
    ..._fr,
    ..._de,
    ..._pt,
  ];
}

